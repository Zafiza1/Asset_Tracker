import { useMutation, useQueryClient } from '@tanstack/react-query'
import { useState } from 'react'
import { useForm } from 'react-hook-form'
import { Button } from '../../components/ui/Button'
import { Alert } from '../../components/ui/Feedback'
import { Field, Input, Select, Textarea } from '../../components/ui/Field'
import { Modal } from '../../components/ui/Modal'
import { api } from '../../lib/api/client'
import type { Resource } from '../../lib/api/types'
import { applyApiErrors } from '../../lib/forms'
import { toOptions, useOptions } from '../master/options'
import { assetStatusLabel, initialStatuses, type Asset } from './api'

type Values = {
  name: string
  serial_number: string
  category_id: string
  location_id: string
  condition_id: string
  status: string
  acquisition_date: string
  acquisition_cost: string
  description: string
}

/** Fields editable after registration; location/status/condition change through transactions. */
const EDITABLE: (keyof Values)[] = ['name', 'serial_number', 'category_id', 'acquisition_date', 'acquisition_cost', 'description']

/**
 * Register a new asset or edit its descriptive data. The asset number is generated by the
 * system and is never entered by the user.
 */
export function AssetFormModal({ asset, onClose, onSaved }: { asset?: Asset; onClose: () => void; onSaved?: (asset: Asset) => void }) {
  const queryClient = useQueryClient()
  const [formError, setFormError] = useState<string | null>(null)
  const categories = toOptions(useOptions('/tenant-masters/categories').data)
  const locations = toOptions(useOptions('/locations').data)
  const conditions = toOptions(useOptions('/tenant-masters/conditions').data)

  const { register, handleSubmit, setError, formState } = useForm<Values>({
    defaultValues: {
      name: asset?.name ?? '',
      serial_number: asset?.serial_number ?? '',
      category_id: asset?.category_id ?? '',
      location_id: '',
      condition_id: '',
      status: 'available',
      acquisition_date: asset?.acquisition_date ?? '',
      acquisition_cost: asset?.acquisition_cost ?? '',
      description: asset?.description ?? '',
    },
  })

  const save = useMutation({
    mutationFn: (values: Values) => {
      const keys = asset ? EDITABLE : (Object.keys(values) as (keyof Values)[])
      const payload: Record<string, unknown> = Object.fromEntries(keys.map((k) => [k, values[k].trim() === '' ? null : values[k].trim()]))
      return asset
        ? api.patch<Resource<Asset>>(`/assets/${asset.id}`, { ...payload, lock_version: asset.lock_version })
        : api.post<Resource<Asset>>('/assets', payload)
    },
    onSuccess: async (res) => {
      await Promise.all(['/assets', '/dashboard', '/transactions'].map((key) => queryClient.invalidateQueries({ queryKey: [key] })))
      onSaved?.(res.data)
      onClose()
    },
    onError: (e) => setFormError(applyApiErrors(e, setError)),
  })

  const err = (name: keyof Values) => formState.errors[name]?.message

  return (
    <Modal
      open
      title={asset ? `Ubah ${asset.name}` : 'Tambah aset'}
      onClose={onClose}
      footer={
        <>
          <Button variant="secondary" onClick={onClose}>
            Batal
          </Button>
          <Button type="submit" form="asset-form" loading={save.isPending}>
            Simpan
          </Button>
        </>
      }
    >
      <form id="asset-form" noValidate className="space-y-4" onSubmit={handleSubmit((v) => (setFormError(null), save.mutate(v)))}>
        {formError && <Alert tone="error">{formError}</Alert>}
        {asset ? (
          <p className="text-sm text-slate-600">
            Nomor aset <span className="font-mono">{asset.asset_number}</span> tidak dapat diubah. Lokasi, status, dan kondisi diubah lewat transaksi agar riwayatnya tercatat.
          </p>
        ) : (
          <p className="text-sm text-slate-600">Nomor aset dibuat otomatis oleh sistem setelah disimpan.</p>
        )}

        <Field label="Nama aset" required error={err('name')}>
          {(p) => <Input {...p} {...register('name', { required: 'Nama aset wajib diisi.' })} />}
        </Field>
        <div className="grid gap-4 sm:grid-cols-2">
          <Field label="Nomor seri / kode aset" error={err('serial_number')} hint="Kode milik organisasi atau nomor seri pabrik (opsional, harus unik).">
            {(p) => <Input {...p} {...register('serial_number')} />}
          </Field>
          <Field label="Kategori" required error={err('category_id')}>
            {(p) => (
              <Select {...p} {...register('category_id', { required: 'Kategori wajib dipilih.' })}>
                <option value="">— Pilih —</option>
                {categories.map((o) => (
                  <option key={o.value} value={o.value}>
                    {o.label}
                  </option>
                ))}
              </Select>
            )}
          </Field>
        </div>

        {!asset && (
          <div className="grid gap-4 sm:grid-cols-3">
            <Field label="Lokasi" error={err('location_id')}>
              {(p) => (
                <Select {...p} {...register('location_id')}>
                  <option value="">— Tanpa lokasi —</option>
                  {locations.map((o) => (
                    <option key={o.value} value={o.value}>
                      {o.label}
                    </option>
                  ))}
                </Select>
              )}
            </Field>
            <Field label="Kondisi" error={err('condition_id')}>
              {(p) => (
                <Select {...p} {...register('condition_id')}>
                  <option value="">— Belum dinilai —</option>
                  {conditions.map((o) => (
                    <option key={o.value} value={o.value}>
                      {o.label}
                    </option>
                  ))}
                </Select>
              )}
            </Field>
            <Field label="Status" error={err('status')}>
              {(p) => (
                <Select {...p} {...register('status')}>
                  {initialStatuses.map((s) => (
                    <option key={s} value={s}>
                      {assetStatusLabel[s]}
                    </option>
                  ))}
                </Select>
              )}
            </Field>
          </div>
        )}

        <div className="grid gap-4 sm:grid-cols-2">
          <Field label="Tanggal perolehan" error={err('acquisition_date')}>
            {(p) => <Input {...p} type="date" {...register('acquisition_date')} />}
          </Field>
          <Field label="Nilai perolehan (Rp)" error={err('acquisition_cost')}>
            {(p) => <Input {...p} type="number" min={0} step="1" inputMode="numeric" {...register('acquisition_cost')} />}
          </Field>
        </div>
        <Field label="Deskripsi & informasi tambahan" error={err('description')}>
          {(p) => <Textarea {...p} rows={3} {...register('description')} />}
        </Field>
      </form>
    </Modal>
  )
}

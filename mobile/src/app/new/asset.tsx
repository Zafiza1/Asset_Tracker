import { router, useFocusEffect } from 'expo-router'
import { useCallback, useEffect, useState } from 'react'
import { ActivityIndicator, KeyboardAvoidingView, Platform, Pressable, ScrollView, StyleSheet, Text, View } from 'react-native'
import { SafeAreaView } from 'react-native-safe-area-context'
import { AttributeFields, Chips, DateInput, Field, Input, Select } from '@/components/form'
import { Alert, Button, colors } from '@/components/ui'
import { errorMessage } from '@/lib/api'
import { announce, fieldErrors, formError, useMasterOptions } from '@/lib/forms'
import { useSession } from '@/lib/session'
import { assetStatusLabel, INITIAL_STATUSES, type Asset, type AssetStatus, type AttributeValue, type CategoryAttribute } from '@/lib/types'

export { ErrorBoundary } from '@/components/ErrorBoundary'

/** Default yes/no field of every category; only meaningful with the Barcode module on (as useAssetFields on the web). */
const BARCODE_FIELD = 'Barcode'

/**
 * Register an asset, as "Tambah aset" in Pendataan Aset on the web. The asset number is
 * generated by the system. Users without approval.manage submit the registration for approval.
 */
export default function NewAssetScreen() {
  const { get, post, can, hasModule } = useSession()
  const categories = useMasterOptions('/tenant-masters/categories', false)
  const locations = useMasterOptions('/locations', false)
  const canAddMasters = can('master.tenant.create')

  const [name, setName] = useState('')
  const [serial, setSerial] = useState('')
  const [categoryId, setCategoryId] = useState<string | null>(null)
  const [locationId, setLocationId] = useState<string | null>(null)
  const [status, setStatus] = useState<AssetStatus>('in_use')
  const [acquisitionDate, setAcquisitionDate] = useState('')
  const [acquisitionCost, setAcquisitionCost] = useState('')
  const [description, setDescription] = useState('')
  const [attributes, setAttributes] = useState<Record<string, AttributeValue>>({})

  const [fields, setFields] = useState<CategoryAttribute[]>([])
  const [fieldsState, setFieldsState] = useState<{ loading: boolean; error: string | null }>({ loading: false, error: null })
  const [errors, setErrors] = useState<Record<string, string>>({})
  const [error, setError] = useState<string | null>(null)
  const [saving, setSaving] = useState(false)

  // Coming back from "Tambah lokasi/kategori" shows the new record (when it was applied directly).
  const { reload: reloadCategories } = categories
  const { reload: reloadLocations } = locations
  useFocusEffect(
    useCallback(() => {
      reloadCategories()
      reloadLocations()
    }, [reloadCategories, reloadLocations]),
  )

  // The category decides which extra fields the asset has.
  const loadFields = useCallback(async () => {
    if (!categoryId) return setFields([])
    setFieldsState({ loading: true, error: null })
    try {
      const rows = (await get<{ data: CategoryAttribute[] }>(`/tenant-masters/categories/${categoryId}/attributes`)).data
      setFields(hasModule('barcode') ? rows : rows.filter((f) => !(f.is_default && f.label === BARCODE_FIELD)))
      setFieldsState({ loading: false, error: null })
    } catch (e) {
      setFields([])
      setFieldsState({ loading: false, error: errorMessage(e) })
    }
  }, [categoryId, get, hasModule])

  useEffect(() => {
    loadFields()
  }, [loadFields])

  const validate = () => {
    const local: Record<string, string> = {}
    if (!name.trim()) local.name = 'Nama aset wajib diisi.'
    if (!categoryId) local.category_id = 'Kategori wajib dipilih.'
    if (!locationId) local.location_id = 'Lokasi wajib dipilih.'
    if (acquisitionDate && !/^\d{4}-\d{2}-\d{2}$/.test(acquisitionDate)) local.acquisition_date = 'Format tanggal TTTT-BB-HH, mis. 2026-01-31.'
    if (acquisitionCost && !/^\d+(\.\d+)?$/.test(acquisitionCost)) local.acquisition_cost = 'Isi dengan angka tanpa titik pemisah ribuan.'
    for (const f of fields) {
      const v = attributes[f.key]
      if (f.is_required && (v === null || v === undefined || v === '' || (Array.isArray(v) && v.length === 0))) local[`attributes.${f.key}`] = `${f.label} wajib diisi.`
    }
    return local
  }

  const submit = async () => {
    const local = validate()
    setErrors(local)
    setError(Object.keys(local).length ? 'Periksa kembali isian yang ditandai.' : null)
    if (Object.keys(local).length) return

    setSaving(true)
    try {
      const response = await post<{ data: Asset }>('/assets', {
        name: name.trim(),
        serial_number: serial.trim() || null,
        category_id: categoryId,
        location_id: locationId,
        status,
        acquisition_date: acquisitionDate || null,
        acquisition_cost: acquisitionCost || null,
        description: description.trim() || null,
        attributes: Object.fromEntries(fields.map((f) => [f.key, attributes[f.key] ?? null])),
      })
      announce(response, {
        title: 'Aset ditambahkan',
        message: 'No Aset dibuat oleh sistem.',
        done: (asset) =>
          // The detail screen looks assets up by number, which needs the Barcode module.
          hasModule('barcode') ? router.replace({ pathname: '/asset/[code]', params: { code: asset.data.asset_number } }) : router.back(),
      })
    } catch (e) {
      setErrors(fieldErrors(e))
      setError(formError(e))
    } finally {
      setSaving(false)
    }
  }

  const attributeErrors = Object.fromEntries(
    Object.entries(errors)
      .filter(([k]) => k.startsWith('attributes.'))
      .map(([k, m]) => [k.slice('attributes.'.length), m]),
  )

  return (
    <SafeAreaView style={{ flex: 1, backgroundColor: colors.background }} edges={['bottom']}>
      <KeyboardAvoidingView style={{ flex: 1 }} behavior={Platform.OS === 'ios' ? 'padding' : undefined}>
        <ScrollView contentContainerStyle={styles.container} keyboardShouldPersistTaps="handled">
          <Text style={styles.muted}>No Aset dibuat otomatis oleh sistem setelah disimpan.</Text>
          {error && <Alert>{error}</Alert>}

          <Field label="Nama aset" required error={errors.name}>
            <Input value={name} onChangeText={setName} invalid={!!errors.name} maxLength={150} />
          </Field>
          <Field label="No Seri" error={errors.serial_number} hint="Nomor seri pabrik atau kode lama (harus unik bila diisi).">
            <Input value={serial} onChangeText={setSerial} autoCorrect={false} invalid={!!errors.serial_number} maxLength={100} />
          </Field>

          <Field label="Kategori" required error={errors.category_id ?? categories.error ?? undefined}>
            <Select
              title="Pilih kategori"
              value={categoryId}
              options={categories.options}
              onChange={(v) => (setCategoryId(v), setAttributes({}))}
              loading={categories.loading && categories.options.length === 0}
              invalid={!!errors.category_id}
            />
            {canAddMasters && <AddLink label="Tambah kategori baru" onPress={() => router.push('/new/category')} />}
          </Field>

          <Field label="Lokasi" required error={errors.location_id ?? locations.error ?? undefined}>
            <Select
              title="Pilih lokasi"
              value={locationId}
              options={locations.options}
              onChange={setLocationId}
              loading={locations.loading && locations.options.length === 0}
              invalid={!!errors.location_id}
            />
            {canAddMasters && <AddLink label="Tambah lokasi baru" onPress={() => router.push('/new/location')} />}
          </Field>

          <Field label="Status" error={errors.status}>
            <Chips value={[status]} options={INITIAL_STATUSES.map((s) => ({ value: s, label: assetStatusLabel[s] }))} onChange={(v) => v[0] && setStatus(v[0] as AssetStatus)} />
          </Field>

          {fieldsState.loading ? (
            <ActivityIndicator color={colors.brand} />
          ) : fieldsState.error ? (
            <View style={{ gap: 8 }}>
              <Alert title="Atribut kategori gagal dimuat">{fieldsState.error}</Alert>
              <Button title="Coba lagi" variant="secondary" onPress={loadFields} />
            </View>
          ) : (
            <AttributeFields fields={fields} values={attributes} errors={attributeErrors} onChange={(key, value) => setAttributes((c) => ({ ...c, [key]: value }))} />
          )}

          <Field label="Tanggal perolehan" error={errors.acquisition_date}>
            <DateInput value={acquisitionDate} onChange={setAcquisitionDate} invalid={!!errors.acquisition_date} />
          </Field>
          <Field label="Harga perolehan (Rp)" error={errors.acquisition_cost}>
            <Input value={acquisitionCost} onChangeText={(t) => setAcquisitionCost(t.replace(/[^0-9]/g, ''))} keyboardType="number-pad" invalid={!!errors.acquisition_cost} />
          </Field>
          <Field label="Deskripsi" error={errors.description}>
            <Input value={description} onChangeText={setDescription} multiline maxLength={2000} invalid={!!errors.description} />
          </Field>

          {!can('approval.manage') && <Text style={styles.muted}>Aset baru diajukan dulu dan masuk daftar aset setelah disetujui Super Admin atau Supervisor.</Text>}
          <Button title="Simpan" onPress={submit} loading={saving} />
        </ScrollView>
      </KeyboardAvoidingView>
    </SafeAreaView>
  )
}

function AddLink({ label, onPress }: { label: string; onPress: () => void }) {
  return (
    <Pressable onPress={onPress} accessibilityRole="link" hitSlop={8} style={{ alignSelf: 'flex-start', paddingVertical: 4 }}>
      <Text style={{ color: colors.brand, fontWeight: '600' }}>+ {label}</Text>
    </Pressable>
  )
}

const styles = StyleSheet.create({
  container: { padding: 16, gap: 16, paddingBottom: 40 },
  muted: { color: colors.muted, fontSize: 13 },
})
